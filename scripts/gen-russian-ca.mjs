// Builds src/max/russianCa.generated.ts from certs/*.crt — the Russian state CA certificates MAX's
// TLS chain needs, embedded in the code so the bridge does not depend on finding certs/ at run time
// (a copy run from another folder, or missing files, failed every connection to MAX — 2026-11-22).
// certs/ stays the readable source (see certs/README.md). Run after changing anything in certs/;
// tests/certs.test.ts fails while the two differ.
import fs from 'node:fs';
import path from 'node:path';

export function readCertsDir(dir = 'certs') {
  return fs
    .readdirSync(dir)
    .filter((f) => f.endsWith('.crt'))
    .sort()
    .map((f) => ({ file: f, pem: fs.readFileSync(path.join(dir, f), 'utf8').replace(/\r\n/g, '\n').trim() + '\n' }));
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve('scripts/gen-russian-ca.mjs')) {
  const certs = readCertsDir();
  const body = [
    '// Generated by scripts/gen-russian-ca.mjs from certs/*.crt — do not edit by hand.',
    '// tests/certs.test.ts checks that it matches certs/.',
    'export const RUSSIAN_CA_PEMS: readonly { file: string; pem: string }[] = [',
    ...certs.map((c) => `  { file: ${JSON.stringify(c.file)}, pem: ${JSON.stringify(c.pem)} },`),
    '];',
    '',
  ].join('\n');
  fs.writeFileSync('src/max/russianCa.generated.ts', body);
  console.log(`src/max/russianCa.generated.ts: ${certs.map((c) => c.file).join(', ')}`);
}
